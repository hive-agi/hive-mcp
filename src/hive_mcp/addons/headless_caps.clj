;; =============================================================================
;; IHookable -- re-export from hive-spi.addon.headless-caps
;; =============================================================================

(def IHookable caps/IHookable)

(defn register-hooks! [this ling-id hooks-map] (caps/register-hooks! this ling-id hooks-map))
(defn active-hooks [this ling-id] (caps/active-hooks this ling-id))

;; =============================================================================
;; ICheckpointable -- re-export
;; =============================================================================

(def ICheckpointable caps/ICheckpointable)

(defn checkpoint! [this ling-id] (caps/checkpoint! this ling-id))
(defn rewind! [this ling-id checkpoint-id] (caps/rewind! this ling-id checkpoint-id))

;; =============================================================================
;; ISubagentHost -- re-export
;; =============================================================================

(def ISubagentHost caps/ISubagentHost)

(defn register-subagents! [this ling-id agent-defs] (caps/register-subagents! this ling-id agent-defs))
(defn list-subagents [this ling-id] (caps/list-subagents this ling-id))

;; =============================================================================
;; IBudgetGuardable -- re-export
;; =============================================================================

(def IBudgetGuardable caps/IBudgetGuardable)

(defn set-budget! [this ling-id max-usd] (caps/set-budget! this ling-id max-usd))
(defn budget-status [this ling-id] (caps/budget-status this ling-id))

;; =============================================================================
;; Capability registry -- re-export
;; =============================================================================

(def capability-protocols caps/capability-protocols)

(defn provided-capabilities [backend] (caps/provided-capabilities backend))

;; =============================================================================
;; Contracts
;; =============================================================================
;; The backend is a protocol instance (a port, never generated by a test) and
;; the hook / subagent maps and results are shapes the backend defines, so they
;; stay open. `provided-capabilities` mirrors the hive-spi contract.

(m/=> register-hooks! [:=> [:cat :any :any :any] :any])
(m/=> active-hooks [:=> [:cat :any :any] :any])
(m/=> checkpoint! [:=> [:cat :any :any] :any])
(m/=> rewind! [:=> [:cat :any :any :any] :any])
(m/=> register-subagents! [:=> [:cat :any :any :any] :any])
(m/=> list-subagents [:=> [:cat :any :any] :any])
(m/=> set-budget! [:=> [:cat :any :any :any] :any])
(m/=> budget-status [:=> [:cat :any :any] :any])
(m/=> provided-capabilities
      [:=> [:cat :any] [:set (into [:enum] (keys capability-protocols))]])
