(ns hive-mcp.swarm.datascript.schema-test
  "Facets for the schema compat shim (hive-mcp.swarm.datascript.schema): every public fn
   delegates to the same-named var of hive-datascript.swarm.schema. Offline (no swarm
   library, this tree) a call raises addon-missing naming the var it reached
   for, and a delegated load-time value is nil; the golden, the property and
   the mutants pin that. The behaviour itself runs in test-swarm/.
   Its value schemas (Slave, Task, ClaimInfo, ...) are hive-mcp's own and
   are generated by the store contract gate."
  (:require [clojure.test.check.clojure-test :refer [defspec]]
            [clojure.test.check.properties :as prop]
            [hive-mcp.swarm.datascript.schema]
            [hive-mcp.test.shim-facets :as sf]
            [hive-test.golden :as golden]
            [hive-test.mutation :as hmut]))

