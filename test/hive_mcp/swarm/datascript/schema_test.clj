(def ^:private shim 'hive-mcp.swarm.datascript.schema)
(def ^:private target "hive-datascript.swarm.schema")
(def ^:private overrides {})
(def ^:private golden-path "test/golden/hive-mcp/swarm/datascript/schema-delegation.edn")

(golden/deftest-golden schema-delegation-golden
  golden-path
  (sf/offline-golden 'hive-mcp.swarm.datascript.schema-test golden-path
                     #(sf/delegation-table shim (sf/contracted shim))))

(defspec every-schema-call-reaches-its-namesake 100
  (prop/for-all [[sym args] (sf/call-gen shim (sf/contracted shim))]
    (sf/reaches-expected? shim target overrides sym args)))

;; Offline only: with the library present the call does real work.
(when (sf/offline?)
  (hmut/deftest-mutations claude-model-delegation-mutations
    hive-mcp.swarm.datascript.schema/claude-model?
    (sf/delegation-mutants shim 'claude-model? nil)
    (sf/delegation-check shim 'claude-model? (sf/expected target overrides 'claude-model?))))
