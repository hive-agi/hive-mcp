(defn- leaf [tag] (fn [_] {:type "text" :text tag}))

(def ^:private tree
  {:status {:_handler (leaf "status") :list (leaf "status list")}
   :spawn  (leaf "spawn")
   :deep   {:a {:b (leaf "deep a b")}}})

(def ^:private Command
  [:or :nil [:enum "" "   " "status" "status list" " spawn  " "deep a b" "deep a" "nope" "status nope"]])

(deftrifecta-from-schema parse-command-splits-on-whitespace
  #'cli/parse-command
  {:in [:cat Command]
   :out [:maybe [:vector :keyword]]
   :rel (fn [[c] out]
          (if (str/blank? c)
            (nil? out)
            (= out (mapv keyword (str/split (str/trim c) #"\s+")))))
   :golden-path "test/golden/hive-mcp/tools/cli-parse-command.edn"
   :num-tests 100})

(def ^:private paths-by-resolution
  "The Path members grouped by the resolution kind each one is written to
   reach. A uniform pick over the eight members drew :tree and :error one
   time in eight each, which sat at the classify floor of 200/12."
  {:handler (mapv cli/parse-command ["status" "status list" "spawn" "deep a b"
                                     "status nope" "spawn extra"])
   :tree    [(cli/parse-command "deep a")]
   :error   [(cli/parse-command "nope")]})

(def ^:private Path
  "Every path above, generated by picking the resolution kind first, so each
   kind is drawn a third of the time."
  [:and {:gen/schema [:tuple (into [:enum] (keys paths-by-resolution)) nat-int?]
         :gen/fmap (fn [[k i]] (let [ps (paths-by-resolution k)] (nth ps (mod i (count ps)))))}
   (into [:enum] (mapcat val) paths-by-resolution)])

(deftrifecta-from-schema resolve-handler-walks-the-tree
  #'cli/resolve-handler
  {:in [:cat [:= {} tree] Path]
   :out cli/Resolution
   :rel (fn [[_ p] out]
          (case p
            [:status]       (= "status" (:text ((:handler out) {})))
            [:status :list] (= "status list" (:text ((:handler out) {})))
            [:status :nope] (= [:nope] (:remaining out))
            [:spawn]        (= [] (:remaining out))
            [:spawn :extra] (= [:extra] (:remaining out))
            [:deep :a :b]   (= "deep a b" (:text ((:handler out) {})))
            [:deep :a]      (contains? out :tree)
            [:nope]         (= :not-found (:error out))))
   :classify (fn [_ out] (cond (:handler out) :handler (:tree out) :tree :else :error))
   :classify-domain #{:handler :tree :error}
   :num-tests 200})


(deftest resolve-handler-coverage-has-margin
  ;; 4000 draws keep the measured share within a few points of the true one,
  ;; so this is stable without a pinned seed.
  (is (= {} (margin/thin-variants [:cat [:= {} tree] Path] #'cli/resolve-handler
                                  (fn [_ out] (cond (:handler out) :handler (:tree out) :tree :else :error))
                                  #{:handler :tree :error} 4000))
      "every resolution kind is drawn at least half as often as an even split"))
(golden/deftest-golden help-and-dispatch-golden
  "test/golden/hive-mcp/tools/cli-help.edn"
  (let [h (cli/make-cli-handler tree)]
    {:help      (cli/format-help tree)
     :dispatch  (:text (h {:command "status list"}))
     :default   (:text (h {:command "status"}))
     :verbs     (cli/declared-verbs (with-meta {:x (with-meta {} {::cli/verbs ["A" :b]})} {}) :x)
     :no-verbs  (cli/declared-verbs tree :spawn)}))

(deftest handlers-answer-mcp-responses
  (let [h (cli/make-cli-handler tree)
        b (cli/make-batch-handler tree)]
    (is (m/validate core/McpResponse (h {:command "nope"})))
    (is (:isError (h {:command "nope"})))
    (is (m/validate core/McpResponse (b {:operations [{:command "spawn"} {:command "zz"}]})))
    (is (:isError (b {})))))
